# (2) __name__ 전역 변수 정체
    # 파이썬은 코드 실행 시 __name__이라는 비가시성 전역변수를
    # 내부에 자동 생성하고 문자열 값 넣음
    # 여기 들어가는 값은 파일 실행 형태에 따라 결정.
    
    # - 최소 실행 메인 파일: 사용자가 직접 실행시킨
                            # 메인 진입점 파일의 __name__변수에는
                            # 무적권 __main__이라는 값이 강제세팅 됨.
    # - 임포트된 모듈 파일: 메인 파일에 의해 import되어 올라온
                            # 모듈 파일의 __name__ 변수에는
                            # 해당 모듈의 실제 이름(파일명)이
