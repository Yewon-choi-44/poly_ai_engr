# 12.4 생성자와 인스턴스 변수

# (1) 생성자: __init__() 메서드
    #  객체가 메모리에 새로 생성될 댸 파이썬 엔진에 의해
    #  자동으로 즉각 실행되는 특수한 초기화 메서드(생성자)
    #  용도: 객체 생성시 가져야 할 초기속성 변수(이름,색상,나이 등)
            # 을 매개변수로 받아와 강제로 세팅 시 사용.
            


class Cat:
    def __init__(self, name, color="흰색"):
        self.name = name #인스턴스 변수 name 생성 및 초기화
        self.color = color # 인스턴스 변수 color 생성 및 초기화
    def meow(self):
        # self를 붙여 인스턴스 고유 변수값 호출
        print(f"내 이름은 {self.name}, 색깔은 {self.color}, 야옹야옹")
        
# 인스턴스 별로 서로 다른 속성을 부여하며 생성
nabi = Cat("나비", "검정색")
nero = Cat('네로')

nabi.meow()
nero.meow()